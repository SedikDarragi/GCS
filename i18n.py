_current_lang = None


def _load_lang_from_disk():
    global _current_lang
    if _current_lang is not None:
        return _current_lang
    # try settings.json
    try:
        if os.path.exists(SETTINGS_PATH):
            with open(SETTINGS_PATH, "r", encoding="utf-8") as f:
                data = json.load(f)
                lang = data.get("language", DEFAULT_LANG)
                if lang in SUPPORTED_LANGS:
                    _current_lang = lang
                    return _current_lang
    except Exception:
        pass
    _current_lang = DEFAULT_LANG
    return _current_lang


def get_language():
    """Return current language code (en/fr). Defaults to en."""
    return _load_lang_from_disk()


def set_language(lang):
    """Persist language and update runtime. lang must be en or fr."""
    global _current_lang
    if lang not in SUPPORTED_LANGS:
        raise ValueError(f"Unsupported language: {lang}")
    _current_lang = lang
    # persist
    try:
        data = {}
        if os.path.exists(SETTINGS_PATH):
            try:
                with open(SETTINGS_PATH, "r", encoding="utf-8") as f:
                    data = json.load(f) or {}
            except Exception:
                data = {}
        data["language"] = lang
        with open(SETTINGS_PATH, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except Exception:
        pass
    return _current_lang


def t(key, lang=None, **kwargs):
    """
    Translate key to current language.
    Falls back to English, then to key itself.
    Supports str.format(**kwargs) interpolation.
    """
    if lang is None:
        lang = get_language()
    # try requested lang
    val = TRANSLATIONS.get(lang, {}).get(key)
    if val is None:
        # fallback to English
        val = TRANSLATIONS.get("en", {}).get(key)
    if val is None:
        # fallback to French (original)
        val = TRANSLATIONS.get("fr", {}).get(key)
    if val is None:
        return key
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


# convenient alias
_ = t
